export const themeOptions: Array<{
  id: ThemeId;
  label: string;
  description: string;
  mode: 'dark' | 'light' | 'system';
  pack: ThemeTokens['pack'];
}> = [
  { id: 'system', label: '跟随系统', description: '仅解析默认深色 / 浅色', mode: 'system', pack: 'default' },
  ...Object.values(themes).map((theme) => ({
    id: theme.id as ThemeId,
    label: theme.label,
    description: theme.description,
    mode: theme.mode,
    pack: theme.pack,
  })),
];

export function resolveTheme(id: ThemeId, prefersDark: boolean): ThemeTokens {
  if (id === 'system') return prefersDark ? themes.dark : themes.light;
  return themes[id];
}
